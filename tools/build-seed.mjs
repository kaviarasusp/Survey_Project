// Copies data/*.xml into js/seed-data.js so the demo also works when index.html
// is opened directly from disk (file://), where browsers block loading the XML files.
// Run after editing anything in data/:   node tools/build-seed.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const names = ['lookups', 'customers', 'questions', 'surveys'];
const seed = Object.fromEntries(names.map((n) => [n, fs.readFileSync(path.join(root, 'data', `${n}.xml`), 'utf8')]));
const out = `// Generated by tools/build-seed.mjs from data/*.xml. Do not edit by hand.\n// Used only when the XML files can't be fetched (index.html opened from disk).\nwindow.A4U_SEED = ${JSON.stringify(seed, null, 2)};\n`;
fs.writeFileSync(path.join(root, 'js', 'seed-data.js'), out);
console.log(`Wrote js/seed-data.js (${names.length} files)`);
